export const hotelsById: Record<string, Hotel> = Object.fromEntries(hotels.map((h) => [h.id, h]));

export function getHotel(id: string): Hotel {
  const hotel = hotelsById[id];
  if (!hotel) {
    throw new Error(`Unknown hotel id: ${id}`);
  }
  return hotel;
}

export function hotelsInCity(city: Hotel["city"]): Hotel[] {
  return hotels.filter((h) => h.city === city).sort((a, b) => a.nightlyPkr - b.nightlyPkr);
}
